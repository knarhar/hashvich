/**
 * Fetch the latest Central Bank of Armenia exchange rates into
 * src/data/cba-latest.json, before the site is built.
 *
 * The CBA API sends no CORS headers, so a visitor's browser cannot call it;
 * the site carries the rates of its last build instead. The deploy workflow
 * runs this before every build and on a schedule (see
 * .github/workflows/deploy.yml). The committed file is only the fallback for
 * local builds and the type check.
 *
 * Fails loudly on any problem: a failed fetch stops the deploy, so the site
 * keeps the rates of its last good build instead of older committed ones.
 *
 * No dependencies: Node's own fetch, and a regular expression over the small,
 * fixed SOAP response.
 */

import { writeFile } from "node:fs/promises";

const ENDPOINT = "https://api.cba.am/exchangerates.asmx";
const OUT = new URL("../src/data/cba-latest.json", import.meta.url);

const body =
  '<?xml version="1.0" encoding="utf-8"?>' +
  '<soap:Envelope xmlns:soap="http://schemas.xmlsoap.org/soap/envelope/">' +
  '<soap:Body><ExchangeRatesLatest xmlns="http://www.cba.am/" /></soap:Body>' +
  "</soap:Envelope>";

const response = await fetch(ENDPOINT, {
  method: "POST",
  headers: {
    "Content-Type": "text/xml; charset=utf-8",
    SOAPAction: '"http://www.cba.am/ExchangeRatesLatest"',
  },
  body,
  signal: AbortSignal.timeout(30_000),
});
if (!response.ok) throw new Error(`CBA API answered ${response.status}`);
const xml = await response.text();

const date = /<CurrentDate>(\d{4}-\d{2}-\d{2})T/.exec(xml)?.[1];
if (!date) throw new Error("CBA response has no CurrentDate");

const rates = [
  ...xml.matchAll(
    /<ExchangeRate><ISO>([A-Z]{3})<\/ISO><Amount>([\d.]+)<\/Amount><Rate>([\d.]+)<\/Rate>/g,
  ),
].map(([, iso, amount, rate]) => ({ iso, amount: Number(amount), rate: Number(rate) }));

for (const iso of ["USD", "EUR", "RUB"]) {
  const hit = rates.find((r) => r.iso === iso);
  if (!hit || !(hit.rate > 0) || !(hit.amount > 0)) {
    throw new Error(`CBA response has no usable ${iso} rate`);
  }
}

const data = {
  _readme:
    "Generated by scripts/fetch-cba-rates.mjs from the CBA ExchangeRatesLatest call. " +
    "Overwritten before every deploy; do not edit by hand. `rate` is AMD per `amount` units.",
  source_name: "Central Bank of Armenia, api.cba.am ExchangeRatesLatest",
  source_url: ENDPOINT,
  fetched_at: new Date().toISOString(),
  date,
  rates,
};

await writeFile(OUT, JSON.stringify(data, null, 2) + "\n");
console.log(`CBA rates of ${date}: ${rates.length} currencies, $1 = ${rates.find((r) => r.iso === "USD").rate} AMD`);
